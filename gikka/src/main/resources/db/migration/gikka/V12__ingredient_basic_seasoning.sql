-- 기본양념(CONFIRMED_BASIC) — 2026-07-17. "집에 늘 있어서 부족분으로 셀 필요가 없는 양념".
-- 매칭에서 아예 건너뛴다(RecommendRules.classify → Tier.BASIC). CONFIRMED_SEASONING 과의 차이:
--   CONFIRMED_SEASONING = 없을 수 있는 양념(고추장·굴소스·두반장…) → "양념만 부족" 섹션으로 살아남음
--   CONFIRMED_BASIC     = 늘 있는 양념(물·소금·설탕…)            → 부족분에서 제외, 안 보임
--
-- 계기(실측): "완전 가능" 섹션이 구조적으로 항상 0이었다. 115개 레시피 중 48개가 "물"을 재료로
-- 적는데 냉장고에 물을 넣는 사람은 없다. 설탕 44·고춧가루 40·간장 34 도 마찬가지 —
-- 이런 상비 양념 하나만 걸려도 완전 가능에서 탈락했다.
--
-- 실측 효과(오너 냉장고 20개·완료 레시피 115개 기준, 그룹 매칭 함께 적용 시):
--   기본양념 없음  -> 완전가능  3 · 양념만부족 33 · 재료부족 79
--   이 목록 적용   -> 완전가능  9 · 양념만부족 27 · 재료부족 79
-- 기본양념 단독으로는 효과가 거의 없다(0→2). 그룹 매칭과 함께여야 의미가 생긴다.
--
-- 범위는 오너가 사전 화면 [기본] 버튼으로 언제든 조정한다 — 이 시드는 출발점일 뿐이다.
-- "마늘"은 뺐다: 떨어질 수 있는 주재료지 상비 양념이 아니다(실측상 넣어도 결과 동일).
