    '간장', '식용유', '기름',
    '후추', '후춧가루',
    '참기름', '들기름',
    '깨', '통깨', '깨소금',
    '다진마늘', '다진 마늘',
    '고춧가루', '고추가루',
    '식초', '백식초'
);
